    /// <summary>Everything mirroring one of our files, for reporting a failure by file.</summary>
    public static IEnumerable<Mirror> For(string ourFile) =>
        All.Where(m => m.OurFile.Equals(ourFile, StringComparison.OrdinalIgnoreCase));

    /// <summary>Matches "Neow.GenerateInitialOptions" or a full type name, case-insensitively.</summary>
    public static IEnumerable<Mirror> Find(string query)
    {
        var q = query.Trim();
        return All.Where(m =>
            $"{m.GameType}.{m.Method}".Contains(q, StringComparison.OrdinalIgnoreCase)
            || $"{Short(m.GameType)}.{m.Method}".Equals(q, StringComparison.OrdinalIgnoreCase)
            || m.Method.Equals(q, StringComparison.OrdinalIgnoreCase));
    }

    public static string Short(string fullTypeName)
    {
        var name = fullTypeName[(fullTypeName.LastIndexOf('.') + 1)..];
        int tick = name.IndexOf('`');
        return tick < 0 ? name : name[..tick];
    }
