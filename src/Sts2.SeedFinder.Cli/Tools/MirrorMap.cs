namespace Sts2.SeedFinder.Cli.Tools;

/// <summary>
/// One game method we reimplement, and the file that reimplements it.
/// </summary>
/// <param name="GameType">Full type name in sts2.dll.</param>
/// <param name="Method">
/// Method name. Overloads are snapshotted together, because the question is only ever "did any
/// of this change", never "which overload".
/// </param>
/// <param name="OurFile">Repo-relative path of the file that mirrors it.</param>
/// <param name="Decides">What breaks if this changes and we do not follow. Shown to the fixer.</param>
public sealed record Mirror(string GameType, string Method, string OurFile, string Decides);

/// <summary>
